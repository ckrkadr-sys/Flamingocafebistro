import type { Locale } from "../lib/i18n/locales.ts";

export type LocalizedText<TValue> = Record<Locale, TValue>;

export type MenuCategoryTranslation = {
  title: string;
  description?: string;
};

export type MenuItemTranslation = {
  name: string;
  description?: string;
};

export type MenuCategory = {
  id: string;
  order: number;
  image?: string;
  translations: LocalizedText<MenuCategoryTranslation>;
};

export type MenuItem = {
  id: string;
  categoryId: string;
  order: number;
  price: number;
  image?: string;
  imagePath?: string;
  isPopular?: boolean;
  isNew?: boolean;
  allergens?: string[];
  tags?: string[];
  translations: LocalizedText<MenuItemTranslation>;
};

function createMenuItem({
  allergens,
  categoryId,
  id,
  image,
  imagePath,
  isNew,
  isPopular,
  order,
  price,
  tags,
  translations,
}: Readonly<{
  allergens?: string[];
  categoryId: string;
  id: string;
  image?: string;
  imagePath?: string;
  isNew?: boolean;
  isPopular?: boolean;
  order: number;
  price: number;
  tags?: string[];
  translations: LocalizedText<MenuItemTranslation>;
}>): MenuItem {
  return {
    categoryId,
    id,
    ...(image ? { image } : {}),
    ...(imagePath ? { imagePath } : {}),
    ...(isNew ? { isNew } : {}),
    ...(isPopular ? { isPopular } : {}),
    ...(allergens ? { allergens } : {}),
    ...(tags ? { tags } : {}),
    order,
    price,
    translations,
  };
}

