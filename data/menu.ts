import type { Locale } from "../lib/i18n/locales.ts";

export type LocalizedText<TValue> = Record<Locale, TValue>;

export type MenuCategoryTranslation = {
  title: string;
  description?: string;
};

export type MenuItemTranslation = {
  name: string;
  description?: string;
};

export type MenuCategory = {
  id: string;
  order: number;
  image?: string;
  translations: LocalizedText<MenuCategoryTranslation>;
};

export type MenuItem = {
  id: string;
  categoryId: string;
  order: number;
  price: number;
  image?: string;
  isPopular?: boolean;
  isNew?: boolean;
  allergens?: string[];
  tags?: string[];
  translations: LocalizedText<MenuItemTranslation>;
};

function createMenuItem({
  categoryId,
  id,
  name,
  order,
  price,
}: Readonly<{
  categoryId: string;
  id: string;
  name: string;
  order: number;
  price: number;
}>): MenuItem {
  return {
    categoryId,
    id,
    order,
    price,
    translations: {
      tr: { name },
      en: { name },
      ru: { name },
      de: { name },
    },
  };
}

